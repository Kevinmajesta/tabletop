test('measurement, fog, walls and lighting geometry', () => {
  const scene = newScene('Test', 'id');
  assert.equal(distance({ x: 0, y: 0 }, { x: 5, y: 7.5 }, scene.grid), 5);
  assert.ok(Math.abs(distance({ x: 0, y: 0 }, { x: 5, y: 7.5 }, { ...scene.grid, diagonal: 'euclidean' }) - Math.sqrt(50)) < .001);
  scene.tokens.push({ id: 'hero', ownerId: 'p', name: 'Hero', image: '', x: 20, y: 50, visionRange: 60, visionSource: true });
  scene.vision = true;
  assert.ok(visible({ x: 60, y: 50 }, scene, 'p'));
  scene.marks.push({ id: 'wall', ownerId: 'dm', kind: 'wall', a: { x: 40, y: 0 }, b: { x: 40, y: 100 }, text: '' });
  assert.ok(blocked({ x: 20, y: 50 }, { x: 60, y: 50 }, scene.marks));
  scene.marks = [{ id: 'door', ownerId: 'dm', kind: 'door', a: { x: 40, y: 0 }, b: { x: 40, y: 100 }, text: '', open: false }];
  assert.ok(blocked({ x: 20, y: 50 }, { x: 60, y: 50 }, scene.marks), 'closed door blocks vision and movement');
  scene.marks[0].open = true;
  assert.equal(blocked({ x: 20, y: 50 }, { x: 60, y: 50 }, scene.marks), false, 'open door does not block');
  scene.marks = [{ id: 'wall', ownerId: 'dm', kind: 'wall', a: { x: 40, y: 0 }, b: { x: 40, y: 100 }, text: '' }];
  assert.ok(blocked({ x: 20, y: 50 }, { x: 60, y: 50 }, scene.marks));
  assert.equal(visible({ x: 60, y: 50 }, scene, 'p'), false);
  assert.ok(blocked({ x: 40, y: 50 }, { x: 60, y: 50 }, scene.marks));
  assert.ok(blocked({ x: 20, y: 0 }, { x: 60, y: 0 }, scene.marks));
  scene.tokens[0].visionSource = false;
  assert.equal(visible({ x: 30, y: 50 }, scene, 'p'), false);
  scene.tokens[0].visionSource = true;
  scene.fog = true;
  assert.equal(visible({ x: 30, y: 50 }, scene, 'p'), false);
  scene.tokens[0].lightRange = 13;
  assert.ok(visible({ x: 30, y: 50 }, scene, 'p'), 'token light opens manual fog around the player');
  scene.tokens[0].lightRange = 0;
  scene.marks.push({ id: 'fog', ownerId: 'dm', kind: 'reveal', a: { x: 0, y: 0 }, b: { x: 35, y: 100 }, text: '' });
  assert.ok(visible({ x: 30, y: 50 }, scene, 'p'));
  scene.daylight = false;
  assert.equal(visible({ x: 30, y: 50 }, scene, 'p'), false);
  scene.tokens[0].lightRange = 60;
  assert.ok(visible({ x: 30, y: 50 }, scene, 'p'), 'DM-assigned token light illuminates within its range');
  scene.tokens[0].lightRange = 0;
  scene.marks.push({ id: 'light', ownerId: 'dm', kind: 'light', a: { x: 25, y: 50 }, b: { x: 35, y: 50 }, text: '' });
  assert.ok(visible({ x: 30, y: 50 }, scene, 'p'));
});

