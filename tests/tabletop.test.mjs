import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { io } from 'socket.io-client';

test('DM and player share room, enforce map permissions, move tokens, chat and roll', async () => {
  const port = 32000 + Math.floor(Math.random() * 10000);
  const base = `http://127.0.0.1:${port}`;
  const testData = mkdtempSync(path.join(tmpdir(), 'meja-petualang-'));
  const server = spawn(process.execPath, process.env.TEST_DEV ? ['--import', 'tsx', 'server/index.ts'] : ['dist-server/index.js'], { env: { ...process.env, PORT: String(port), DATA_DIR: testData }, stdio: ['ignore', 'pipe', 'pipe'] });
  let serverOutput = '';
  server.stdout.on('data', chunk => { serverOutput += chunk; });
  server.stderr.on('data', chunk => { serverOutput += chunk; });
  const sockets = [];
  try {
    let ready = false;
    for (let i = 0; i < 100; i++) {
      if (server.exitCode !== null) throw new Error(`Server exited unexpectedly: ${serverOutput}`);
      try { await fetch(base); ready = true; break; } catch { await new Promise(resolve => setTimeout(resolve, 100)); }
    }
    assert.ok(ready, `server starts: ${serverOutput}`);
    const created = await fetch(`${base}/api/rooms`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: 'Test Campaign' }) });
    const { id, dmKey } = await created.json();
    assert.ok(id && dmKey);
    const portraits = await fetch(`${base}/api/token-screen`);
    assert.equal(portraits.status, 200);
    const tokenScreen = await portraits.json();
    assert.equal(tokenScreen.portraits.length, 4);
    const lobby = await fetch(`${base}/api/hero-lobby`, { method: 'POST' });
    assert.equal(lobby.status, 200);
    const heroLobby = await lobby.json();
    assert.equal(heroLobby.title, 'The Age of Heroes');
    assert.equal(heroLobby.id, 'AGEOFHEROES');
    assert.ok(heroLobby.dmKey, 'first entrant receives the DM key');
    assert.deepEqual(heroLobby.portraits, tokenScreen.portraits);
    const playerLobby = await fetch(`${base}/api/hero-lobby`, { method: 'POST' });
    assert.equal(playerLobby.status, 200);
    assert.deepEqual(await playerLobby.json(), { id: 'AGEOFHEROES', title: 'The Age of Heroes' });
    const resetLobby = await fetch(`${base}/api/hero-lobby/reset`, { method: 'POST' });
    assert.equal(resetLobby.status, 200);
    assert.deepEqual(await resetLobby.json(), { ok: true });
    const reclaimedLobby = await fetch(`${base}/api/hero-lobby`, { method: 'POST' });
    const reclaimed = await reclaimedLobby.json();
    assert.ok(reclaimed.dmKey, 'reset allows the next entrant to claim DM');
    const connect = async (name, playerId, dmKeyValue) => {
      const socket = io(base);
      sockets.push(socket);
      await new Promise((resolve, reject) => { socket.once('connect', resolve); socket.once('connect_error', reject); });
      const result = await new Promise(resolve => socket.emit('room:join', { roomId: id, name, playerId, playerSecret: `secret-${playerId}`, dmKey: dmKeyValue }, resolve));
      assert.equal(result.ok, true);
      return { socket, result };
    };
    const dm = await connect('DM', 'dm', dmKey);
    const player = await connect('Player', 'player');
    const namedDm = await connect('dm', 'named-dm');
    assert.equal(dm.result.isDM, true);
    assert.equal(player.result.isDM, false);
    assert.equal(namedDm.result.isDM, true);
    const waitState = (socket, condition) => new Promise((resolve, reject) => {
      const timeout = setTimeout(() => { socket.off('room:state', listener); reject(new Error('State update timed out')); }, 2500);
      function listener(state) { if (condition(state)) { clearTimeout(timeout); socket.off('room:state', listener); resolve(state); } }
      socket.on('room:state', listener);
    });
    const image = new Blob([Uint8Array.from([137, 80, 78, 71])], { type: 'image/png' });
    const upload = async (kind, who, key) => {
      const form = new FormData(); form.append('image', image, 'sample.png'); form.append('name', 'Hero');
      return fetch(`${base}/api/rooms/${id}/upload/${kind}`, { method: 'POST', headers: { 'x-player-id': who, 'x-player-secret': `secret-${who}`, 'x-dm-key': key || '' }, body: form });
    };
    assert.equal((await upload('map', 'player')).status, 403);
    const mapState = waitState(player.socket, state => !!state.map);
    assert.equal((await upload('map', 'dm', dmKey)).status, 200);
    assert.ok((await mapState).map.startsWith('/uploads/'));
    const tokenState = waitState(dm.socket, state => state.tokens.length === 1);
    assert.equal((await upload('token', 'player')).status, 200);
    const token = (await tokenState).tokens[0];
    const resizedState = waitState(dm.socket, state => state.tokens[0].size === 2);
    player.socket.emit('token:resize', { id: token.id, size: 2 });
    assert.equal((await resizedState).tokens[0].size, 2);
    const clampedState = waitState(player.socket, state => state.tokens[0].size === 6);
    dm.socket.emit('token:resize', { id: token.id, size: 99 });
    assert.equal((await clampedState).tokens[0].size, 6);
    const outsider = await connect('Other player', 'outsider');
    outsider.socket.emit('token:resize', { id: token.id, size: 3 });
    player.socket.emit('token:resize', { id: token.id, size: 'invalid' });
    await new Promise(resolve => setTimeout(resolve, 100));
    const wrongMove = waitState(dm.socket, state => state.tokens[0].x === 25);
    dm.socket.emit('token:move', { id: token.id, x: 25, y: 30, final: true });
    assert.equal((await wrongMove).tokens[0].size, 6, 'unauthorized and invalid resize ignored');
    const liveMove = new Promise(resolve => dm.socket.once('token:moved', resolve));
    player.socket.emit('token:move', { id: token.id, x: 60, y: 65, final: false });
    assert.deepEqual(await liveMove, { id: token.id, x: 60, y: 65 });
    const movedState = waitState(dm.socket, state => state.tokens[0].x === 75);
    player.socket.emit('token:move', { id: token.id, x: 75, y: 75, final: true });
    const moved = await movedState;
    assert.equal(moved.tokens[0].y, 75);
    const chatState = waitState(dm.socket, state => state.messages.some(m => m.text === 'Halo party'));
    player.socket.emit('chat:send', 'Halo party');
    assert.equal((await chatState).messages.at(-1).name, 'Player');
    const rollState = waitState(player.socket, state => state.messages.some(m => m.kind === 'roll'));
    const animation = socket => new Promise(resolve => socket.once('dice:animation', resolve));
    const dmAnimation = animation(dm.socket);
    const playerAnimation = animation(player.socket);
    dm.socket.emit('dice:roll', '1d20+3');
    const message = (await rollState).messages.at(-1);
    assert.match(message.text, /1d20\+3 → \[\d+\] \+ 3 = \d+/);
    const trajectory = await dmAnimation;
    assert.deepEqual(trajectory, await playerAnimation);
    assert.equal(trajectory.id, message.id);
    assert.deepEqual(trajectory.roll.values, message.roll.values);
    assert.equal(trajectory.roll.total, message.roll.total);
    assert.ok(trajectory.roll.frames.length > 1);
    assert.equal(message.roll.frames, undefined, 'trajectory not persisted into chat history');
    const cooldown = await new Promise(resolve => dm.socket.emit('dice:roll', '1d20', resolve));
    assert.ok(cooldown.error);
    const otherRoom = await (await fetch(`${base}/api/rooms`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).json();
    const other = io(base); sockets.push(other);
    await new Promise((resolve, reject) => { other.once('connect', resolve); other.once('connect_error', reject); });
    await new Promise(resolve => other.emit('room:join', { roomId: otherRoom.id, name: 'Other room', playerId: 'other', playerSecret: 'other-secret' }, resolve));
    await new Promise(resolve => setTimeout(resolve, 1600));
    const pendingRoll = new Promise(resolve => dm.socket.emit('dice:roll', '20d100', resolve));
    await new Promise(resolve => setTimeout(resolve, 50));
    const blockedOther = await new Promise(resolve => other.emit('dice:roll', '20d100', resolve));
    assert.ok(blockedOther.error, 'same caller cannot consume another worker across rooms');
    const pendingResult = await pendingRoll;
    assert.ok(pendingResult.ok || pendingResult.error, 'heavy roll completes or rejects without blocking server');
    const allowedOther = await new Promise(resolve => other.emit('dice:roll', '1d6', resolve));
    assert.equal(allowedOther.ok, true, 'another room can roll after worker is released');
    const rejoin = await new Promise(resolve => player.socket.emit('room:join', { roomId: id, name: 'Imposter', playerId: 'dm', playerSecret: 'wrong' }, resolve));
    assert.ok(rejoin.error);
    const gameAction = (socket, action) => new Promise(resolve => socket.emit('minigame:action', action, resolve));
    assert.ok((await gameAction(player.socket, { type: 'create', kind: 'rps' })).error);
    const createdGame = waitState(player.socket, state => state.minigames?.length === 1);
    assert.equal((await gameAction(dm.socket, { type: 'create', kind: 'rps' })).ok, true);
    const createdGameState = await createdGame;
    const gameToken = createdGameState.minigames[0].tokenId;
    assert.equal(createdGameState.tokens.find(token => token.id === gameToken).name, '???');
    assert.ok((await gameAction(player.socket, { type: { toString: null }, tokenId: gameToken })).error);
    assert.ok((await gameAction(player.socket, { type: 'join', tokenId: gameToken })).error);
    assert.ok((await gameAction(dm.socket, { type: 'start', tokenId: gameToken })).error);
    assert.ok((await gameAction(dm.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'player'] })).error);
    await gameAction(dm.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'outsider'] });
    assert.ok((await gameAction(player.socket, { type: 'start', tokenId: gameToken })).error);
    await gameAction(dm.socket, { type: 'start', tokenId: gameToken });
    const secretChoice = waitState(dm.socket, state => state.minigames[0].choices.player === 'locked');
    await gameAction(player.socket, { type: 'choose', tokenId: gameToken, choice: 'rock' });
    assert.equal((await secretChoice).minigames[0].choices.player, 'locked');
    const resolvedGame = waitState(player.socket, state => state.minigames[0].phase === 'finished');
    await gameAction(outsider.socket, { type: 'choose', tokenId: gameToken, choice: 'scissors' });
    assert.equal((await resolvedGame).minigames[0].result, 'player');
    for (const kind of ['quiz', 'marbles']) assert.ok((await gameAction(dm.socket, { type: 'create', kind })).error);
    const secondGame = waitState(player.socket, state => state.minigames?.length === 2);
    await gameAction(dm.socket, { type: 'create', kind: 'tictactoe' });
    const gameState = await secondGame;
    const first = gameState.tokens.find(token => token.id === gameToken);
    const second = gameState.tokens.find(token => token.id === gameState.minigames[1].tokenId);
    assert.notDeepEqual([first.x, first.y], [second.x, second.y]);
    await gameAction(dm.socket, { type: 'reset', tokenId: gameToken });
    assert.ok((await gameAction(player.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'outsider'] })).error);
    assert.ok((await gameAction(dm.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'missing'] })).error);
    const declaration = waitState(player.socket, state => state.minigames[0].declaration === 2);
    assert.equal((await gameAction(dm.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'outsider'] })).ok, true);
    assert.deepEqual((await declaration).minigames[0].players, ['player', 'outsider']);
    assert.ok((await gameAction(dm.socket, { type: 'declare', tokenId: second.id })).error);
    const secondDeclaration = waitState(player.socket, state => state.minigames[1].declaration === 1);
    await gameAction(dm.socket, { type: 'declare', tokenId: second.id, players: ['player', 'outsider'] });
    assert.deepEqual((await secondDeclaration).minigames[1].players.sort(), ['outsider', 'player']);
    await gameAction(dm.socket, { type: 'reset', tokenId: gameToken });
    assert.equal((await gameAction(dm.socket, { type: 'declare', tokenId: gameToken, players: ['player', 'dm'] })).ok, true);
    await gameAction(dm.socket, { type: 'start', tokenId: gameToken });
    await gameAction(player.socket, { type: 'choose', tokenId: gameToken, choice: 'scissors' });
    const gmWin = waitState(player.socket, state => state.minigames[0].phase === 'finished' && state.minigames[0].result === 'dm');
    assert.equal((await gameAction(dm.socket, { type: 'choose', tokenId: gameToken, choice: 'rock' })).ok, true);
    assert.equal((await gmWin).minigames[0].result, 'dm');
    const connectFourCreated = waitState(player.socket, state => state.minigames?.some(game => game.kind === 'connectfour'));
    await gameAction(dm.socket, { type: 'create', kind: 'connectfour' });
    const connectFour = (await connectFourCreated).minigames.find(game => game.kind === 'connectfour');
    const spectatorView = waitState(outsider.socket, state => state.minigames.some(game => game.tokenId === connectFour.tokenId && game.declaration === 1));
    await gameAction(dm.socket, { type: 'declare', tokenId: connectFour.tokenId, players: ['player', 'dm'] });
    assert.equal((await spectatorView).minigames.find(game => game.tokenId === connectFour.tokenId).board.length, 42);
    await gameAction(dm.socket, { type: 'start', tokenId: connectFour.tokenId });
    const playerBoard = waitState(player.socket, state => state.minigames.find(game => game.tokenId === connectFour.tokenId)?.board[35] === 'X');
    assert.equal((await gameAction(player.socket, { type: 'drop', tokenId: connectFour.tokenId, column: 0 })).ok, true);
    assert.equal((await playerBoard).minigames.find(game => game.tokenId === connectFour.tokenId).turn, 1);
    assert.ok((await gameAction(outsider.socket, { type: 'drop', tokenId: connectFour.tokenId, column: 1 })).error);
    const mathCreated = waitState(player.socket, state => state.minigames?.some(game => game.kind === 'quickmath'));
    assert.equal((await gameAction(dm.socket, { type: 'create', kind: 'quickmath' })).ok, true);
    const math = (await mathCreated).minigames.find(game => game.kind === 'quickmath');
    const mathDeclared = waitState(player.socket, state => state.minigames.find(game => game.tokenId === math.tokenId)?.declaration === 1);
    assert.equal((await gameAction(dm.socket, { type: 'declare', tokenId: math.tokenId })).ok, true);
    assert.deepEqual((await mathDeclared).minigames.find(game => game.tokenId === math.tokenId).players.sort(), ['dm', 'outsider', 'player']);
    const mathOpen = waitState(player.socket, state => state.minigames.find(game => game.tokenId === math.tokenId)?.phase === 'open');
    const gmMathOpen = waitState(dm.socket, state => state.minigames.find(game => game.tokenId === math.tokenId)?.phase === 'open');
    assert.equal((await gameAction(dm.socket, { type: 'start', tokenId: math.tokenId, question: 'fake', answer: -1 })).ok, true);
    const question = (await mathOpen).minigames.find(game => game.tokenId === math.tokenId);
    assert.equal(Object.hasOwn(question, 'answer'), false);
    assert.equal(Object.hasOwn((await gmMathOpen).minigames.find(game => game.tokenId === math.tokenId), 'answer'), false);
    const match = /^(\d+) ([+−×]) (\d+)$/.exec(question.question);
    assert.ok(match);
    const a = Number(match[1]), b = Number(match[3]);
    const answer = match[2] === '+' ? a + b : match[2] === '−' ? a - b : a * b;
    const submission = { type: 'answer', tokenId: math.tokenId, round: question.round, question: question.turn, answer };
    assert.ok((await gameAction(dm.socket, { ...submission, answer: answer + 1 })).error);
    assert.ok((await gameAction(player.socket, { ...submission, answer: answer + 1 })).error);
    const nextQuestion = waitState(outsider.socket, state => state.minigames.find(game => game.tokenId === math.tokenId)?.turn === 1);
    const responses = await Promise.all([gameAction(player.socket, submission), gameAction(outsider.socket, submission)]);
    assert.equal(responses.filter(response => response.ok).length, 1);
    assert.equal(responses.filter(response => response.error).length, 1);
    const continued = (await nextQuestion).minigames.find(game => game.tokenId === math.tokenId);
    assert.equal(continued.phase, 'open');
    assert.equal(continued.scores.player + continued.scores.outsider + continued.scores.dm, 1);
    const mathRemoved = waitState(player.socket, state => !state.minigames.some(game => game.tokenId === math.tokenId));
    dm.socket.emit('token:remove', math.tokenId);
    assert.equal((await mathRemoved).tokens.some(token => token.id === math.tokenId), false);
    await gameAction(dm.socket, { type: 'create', kind: 'memory' });
    const memoryCreated = await waitState(player.socket, state => state.minigames?.some(game => game.kind === 'memory'));
    const memoryTokenId = memoryCreated.minigames.find(game => game.kind === 'memory').tokenId;
    await gameAction(dm.socket, { type: 'declare', tokenId: memoryTokenId, players: ['player', 'outsider'] });
    await gameAction(dm.socket, { type: 'start', tokenId: memoryTokenId });
    const memoryOpen = await waitState(player.socket, state => state.minigames.find(game => game.tokenId === memoryTokenId)?.phase === 'open');
    const memoryGame = memoryOpen.minigames.find(game => game.tokenId === memoryTokenId);
    assert.equal(memoryGame.memoryBoard.every(card => card === ''), true);
    await gameAction(player.socket, { type: 'flip', tokenId: memoryTokenId, index: 0 });
    const firstFlipPlayer = await waitState(player.socket, state => state.minigames.find(game => game.tokenId === memoryTokenId)?.memoryBoard[0] !== '');
    const firstFlipOutsider = await waitState(outsider.socket, state => state.minigames.find(game => game.tokenId === memoryTokenId)?.turn === 0);
    assert.ok(firstFlipPlayer.minigames.find(game => game.tokenId === memoryTokenId).memoryBoard[0]);
    assert.equal(firstFlipOutsider.minigames.find(game => game.tokenId === memoryTokenId).memoryBoard[0], '');
    await gameAction(player.socket, { type: 'flip', tokenId: memoryTokenId, index: 1 });
    const secondFlipOutsider = await waitState(outsider.socket, state => state.minigames.find(game => game.tokenId === memoryTokenId)?.turn === 1 || state.minigames.find(game => game.tokenId === memoryTokenId)?.scores.player === 1);
    assert.ok(secondFlipOutsider.minigames.find(game => game.tokenId === memoryTokenId).memoryBoard[0]);
  } finally {
    for (const socket of sockets) socket.disconnect();
    server.kill();
    await new Promise(resolve => { if (server.exitCode !== null) resolve(); else server.once('exit', resolve); });
    rmSync(testData, { recursive: true, force: true });
  }
});
